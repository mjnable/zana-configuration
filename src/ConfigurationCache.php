<?php

declare(strict_types=1);

namespace Zana\Configuration;

/**
 * Writes a configuration to a PHP file and loads it back, to skip merging
 * sources on every request in production.
 *
 * The file is PHP, which load() runs: someone who can write to its directory
 * could put code in it. With a key (2.36), write() signs the file and load()
 * runs only a file it signed, and runs the bytes it checked, so the file
 * cannot be swapped after the check. Applications built with
 * ApplicationBuilder::withConfigurationCache() get this from core, with a key
 * derived from security.secret; this class is for configuration used without
 * core.
 */
final class ConfigurationCache
{
    private const string PREFIX = "<?php\n// zana-signature: ";

    /**
     * Write atomically: a temporary file in the same directory, then a rename.
     *
     * @param string|null $key Signs the file (2.36); load() then needs the same key
     * @throws ConfigurationException If the file cannot be written
     */
    public static function write(string $path, ConfigurationInterface $configuration, ?string $key = null): void
    {
        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw ConfigurationException::invalidFile($path, 'cannot be written: the directory cannot be created');
        }

        $body = "\n// Configuration cache generated by Zana. Do not edit.\n\nreturn " . var_export($configuration->all(), true) . ";\n";
        $source = $key === null ? "<?php\n" . $body : self::PREFIX . self::mac(self::key($key), $body) . "\n" . $body;

        $temporary = $path . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($temporary, $source) === false || !rename($temporary, $path)) {
            @unlink($temporary);
            throw ConfigurationException::invalidFile($path, 'cannot be written');
        }

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * The cached configuration, or null if there is no cache file.
     *
     * With a key (2.36), a file without a signature, written without one, is
     * not loaded either (null): build the configuration and write it again. A
     * file with another signature, changed or written with another key, is
     * refused.
     *
     * @throws ConfigurationException If the file does not return an array, or carries another signature
     */
    public static function load(string $path, ?string $key = null): ?Configuration
    {
        if (!is_file($path)) {
            return null;
        }

        if ($key === null) {
            $values = (static fn (string $file): mixed => require $file)($path);
        } else {
            $source = @file_get_contents($path);
            if (!is_string($source) || !str_starts_with($source, self::PREFIX)) {
                return null;
            }
            $end = strpos($source, "\n", strlen(self::PREFIX));
            $body = $end === false ? '' : substr($source, $end + 1);
            $mac = $end === false ? '' : substr($source, strlen(self::PREFIX), $end - strlen(self::PREFIX));
            if (!hash_equals(self::mac(self::key($key), $body), $mac)) {
                throw ConfigurationException::invalidFile($path, 'does not carry the signature of this key: it was changed, or written with another key. It was not loaded');
            }
            $values = self::evaluate($body);
        }
        if (!is_array($values)) {
            throw ConfigurationException::invalidFile($path, 'is not a configuration cache');
        }

        /** @var array<string, mixed> $values */
        return new Configuration($values);
    }

    /**
     * Run the bytes that were checked, rather than include the file again.
     */
    private static function evaluate(string $body): mixed
    {
        return eval($body);
    }

    private static function key(string $key): string
    {
        if ($key === '') {
            throw new \InvalidArgumentException('The key of a configuration cache cannot be empty.');
        }

        return $key;
    }

    private static function mac(string $key, string $body): string
    {
        return hash_hmac('sha256', 'zana-configuration-cache|' . $body, $key);
    }
}
