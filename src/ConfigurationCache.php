<?php

declare(strict_types=1);

namespace Zana\Configuration;

/**
 * Writes a configuration to a PHP file and loads it back, to skip merging
 * sources on every request in production.
 */
final class ConfigurationCache
{
    /**
     * Write atomically: a temporary file in the same directory, then a rename.
     *
     * @throws ConfigurationException If the file cannot be written
     */
    public static function write(string $path, ConfigurationInterface $configuration): void
    {
        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw ConfigurationException::invalidFile($path, 'cannot be written: the directory cannot be created');
        }

        $temporary = $path . '.' . bin2hex(random_bytes(4)) . '.tmp';
        $source = "<?php\n\n// Configuration cache generated by Zana. Do not edit.\n\nreturn " . var_export($configuration->all(), true) . ";\n";

        if (file_put_contents($temporary, $source) === false || !rename($temporary, $path)) {
            @unlink($temporary);
            throw ConfigurationException::invalidFile($path, 'cannot be written');
        }

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * The cached configuration, or null if there is no cache file.
     *
     * @throws ConfigurationException If the file does not return an array
     */
    public static function load(string $path): ?Configuration
    {
        if (!is_file($path)) {
            return null;
        }

        $values = (static fn (string $file): mixed => require $file)($path);
        if (!is_array($values)) {
            throw ConfigurationException::invalidFile($path, 'is not a configuration cache');
        }

        /** @var array<string, mixed> $values */
        return new Configuration($values);
    }
}
